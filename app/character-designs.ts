const DUNGEON_HEAL_SKILL = /治癒|祈り|祝福|福音|鬨|蘇生/;
const DUNGEON_GUARD_SKILL =
  /結界|障壁|城壁|聖壁|防陣|小盾|硬化|装甲|双壁|護り|再生/;
const DUNGEON_AREA_SKILL =
  /乱舞|旋刃|嵐|大潮|大震|薙ぎ|散布|奔流|炎界|毒霧|葬列|暴走|大蛇行|拡散|神楽|天槍陣|冥弾|大術|福音|祝福|大口|爆ぜ|捕食|吸魂|天翔|光波|噴爆|砲式|千矢/;
const DUNGEON_AREA_ATTACK_ROLE = /群撃|三首|双将|双姫|巨神|亡霊機関車/;

const d = (
  name: string,
  role: string,
  element: string,
  skill: string,
  archetype: CombatArchetype,
  lore: string,
  rarity?: DesignRarity,
): CharacterDesign => {
  const skillKind: DesignSkillKind =
    archetype === "healer" || DUNGEON_HEAL_SKILL.test(skill)
      ? "heal"
      : archetype === "support" || DUNGEON_GUARD_SKILL.test(skill)
        ? "guard"
        : "damage";
  return {
    name,
    role,
    element,
    skill,
    archetype,
    lore,
    rarity,
    skillKind,
    attackScope: DUNGEON_AREA_ATTACK_ROLE.test(role) ? "all" : "single",
    skillScope:
      skillKind === "damage" && DUNGEON_AREA_SKILL.test(skill)
        ? "all"
        : "single",
  };
};

